import pandas as pd
import numpy as np
import xgboost as xgb
import matplotlib.pyplot as plt
from sklearn.metrics import mean_absolute_error, r2_score

df= pd.read_csv('/content/hospitalizations.csv')

df.info()

df.describe()

df.head()
df.tail()

df.shape

df.columns

#checking null values

df.isnull().sum()

#duplicates

df.duplicated().sum()

# Clean the data
df["date"] = pd.to_datetime(df["date"], errors="coerce")
print(df)

# Remove invalid dates
df = df.dropna(subset=["date"])
print(df)

# Keep only valid COVID years
df = df[(df["date"].dt.year >= 2020) & (df["date"].dt.year <= 2025)]
print (df)

df.head()

us_data = df[df["location_key"] == "US"].copy()

us_data.head()

# Keep important columns and drop missing values
us_data = us_data.dropna(subset=[
    "current_hospitalized_patients",
    "current_intensive_care_patients",
    "current_ventilator_patients"
])

us_data = us_data.sort_values("date").reset_index(drop=True)

us_data.head()

# FEATURE ENGINEERING
# Lag features
us_data["lag_1"] = us_data["current_hospitalized_patients"].shift(1)
us_data["lag_7"] = us_data["current_hospitalized_patients"].shift(7)
us_data["lag_14"] = us_data["current_hospitalized_patients"].shift(14)
print(us_data)

# Rolling averages
us_data["rolling_7"] = us_data["current_hospitalized_patients"].rolling(7).mean()
us_data["rolling_14"] = us_data["current_hospitalized_patients"].rolling(14).mean()
print(us_data)

# Time features
us_data["day_of_week"] = us_data["date"].dt.dayofweek
us_data["month"] = us_data["date"].dt.month
us_data["year"] = us_data["date"].dt.year
print(us_data)

# Drop NA created by lag/rolling features
us_data = us_data.dropna().reset_index(drop=True)

us_data.head()

# EXPLORATORY VISUALIZATION
# 7-day average for plotting
us_data["hospitalized_7day_avg"] = us_data["current_hospitalized_patients"].rolling(7).mean()

plt.figure(figsize=(15,7))
plt.plot(
    us_data["date"],
    us_data["hospitalized_7day_avg"],
    color="#0077b5",
    linewidth=3,
    label="Hospitalized Patients (7-Day Avg)"
)

plt.title("COVID-19 Hospitalization Trend in the United States", fontsize=18, fontweight="bold")
plt.xlabel("Date")
plt.ylabel("Hospitalized Patients")
plt.legend()
plt.grid(True, linestyle="--", alpha=0.4)
plt.show()

us_data = us_data[us_data["current_hospitalized_patients"] > 0]
us_data = us_data.reset_index(drop=True)

us_data["current_hospitalized_patients"].head(20)

us_data["lag_1"] = us_data["current_hospitalized_patients"].shift(1)
us_data["lag_7"] = us_data["current_hospitalized_patients"].shift(7)

us_data["rolling_7"] = us_data["current_hospitalized_patients"].rolling(7).mean()

us_data = us_data.dropna()

print(us_data)

# DEFINE FEATURES AND TARGET

features = [
    "current_intensive_care_patients",
    "current_ventilator_patients",
    "lag_1",
    "lag_7",
    "lag_14",
    "rolling_7",
    "rolling_14",
    "day_of_week",
    "month",
    "year"
]

X = us_data[features]
y = us_data["current_hospitalized_patients"]

X.head()

y.head()

# train-test split
split_index = int(len(us_data) * 0.8)

X_train = X.iloc[:split_index]
X_test = X.iloc[split_index:]

y_train = y.iloc[:split_index]
y_test = y.iloc[split_index:]

test_dates = us_data["date"].iloc[split_index:]

X_train.shape, X_test.shape

# Train xgboost model
model = xgb.XGBRegressor(
    n_estimators=300,
    learning_rate=0.05,
    max_depth=5,
    subsample=0.8,
    colsample_bytree=0.8,
    random_state=42
)

model.fit(X_train, y_train)

# make predictions
y_pred = model.predict(X_test)

y_pred[:10]

from sklearn.metrics import mean_squared_error

mae = mean_absolute_error(y_test, y_pred)
rmse = np.sqrt(mean_squared_error(y_test, y_pred))
r2 = r2_score(y_test, y_pred)

results = pd.DataFrame({
    "Metric": ["MAE", "RMSE", "R2 Score"],
    "Value": [mae, rmse, r2]
})

results

plt.figure(figsize=(15,7))

plt.plot(test_dates, y_test.values, label="Actual", color="#1f77b4", linewidth=3)
plt.plot(test_dates, y_pred, label="Predicted", color="#ff7f0e", linewidth=3)

plt.title("Actual vs Predicted COVID-19 Hospitalizations (US)", fontsize=18, fontweight="bold")
plt.xlabel("Date")
plt.ylabel("Hospitalized Patients")
plt.legend()
plt.grid(True, linestyle="--", alpha=0.4)
plt.tight_layout()
plt.show()

# FEATURE IMPORTANCE

importance_df = pd.DataFrame({
    "Feature": features,
    "Importance": model.feature_importances_
}).sort_values("Importance", ascending=False)

importance_df

import seaborn as sns

